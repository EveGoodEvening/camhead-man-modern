/** Touch devices have no keyboard: rewrite key names in a player-facing text to the on-screen buttons (P3 round 2;
 *  lens hints, tripod / peek exits, wx hints). Only known keys are touched, never 1× / 3× / 90% / QR. */
const KEY_BTN: Readonly<Record<string, string>> = {
  Q: '闪光', N: '夜景', E: '交互', R: '对照', G: '出示', F: '取景', Tab: '手机', Esc: '返回', J: '手机',
};
export function keyless(text: string): string {
  const btn = (k: string) => `点「${KEY_BTN[k]}」`;
  return text
    .replace(/（夜景 N）/g, `（${btn('N')}）`)
    // P3r2 text: the button already names the thing, so never 「开夜景（点「夜景」）」 / 「点「对照」叠上对照」
    .replace(/(?:开|打开)?(闪光|夜景|对照|出示|取景|手机)（(Tab|Esc|[QNERGFJ])）/g, (m, w: string, k: string) => (KEY_BTN[k] === w ? btn(k) : m))
    .replace(/按 ?R ?叠上对照/g, `${btn('R')}叠上去`)
    .replace(/按 ?H ?问土地/g, '在手机微信里点「求助」问土地')
    .replace(/E \/ Esc/g, 'Esc')
    .replace(/按住左键/g, '按住「快门」')
    .replace(/按左键|左键/g, '点「快门」')
    .replace(/用 ?WASD ?/g, '拖动左半屏，')
    .replace(/按住右键/g, btn('F'))
    .replace(/按 ?(Tab|Esc|[QNERGFJ])(?![A-Za-z0-9]) ?/g, (_m, k: string) => btn(k))
    .replace(/（(Tab|Esc|[QNERGFJ])）/g, (_m, k: string) => `（${btn(k)}）`)
    .replace(/(^|[^A-Za-z])(Tab|Esc)(?![A-Za-z]) ?/g, (_m, p: string, k: string) => `${p}${btn(k)}`);
}
